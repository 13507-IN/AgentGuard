"""Audit logging service for AgentGuard.

Records every proposed action, security inspection decision, and execution result.
Enforces automatic redaction of secrets and truncation of verbose outputs before
persisting records to the database.
"""

from __future__ import annotations

import json
import uuid
from datetime import datetime, timezone
from typing import Any

from agentguard.db import Database
from agentguard.schemas import (
    ActionRequest,
    ActionType,
    ApprovalStatus,
    AuditEntry,
    Decision,
    RiskCategory,
    SecurityDecision,
)

DEFAULT_MAX_OUTPUT_LENGTH = 10240


class AuditLogger:
    """The audit logging service.

    Responsible for persisting inspection decisions and execution outcomes,
    redacting sensitive tokens, and providing filtered query capabilities.
    """

    def __init__(self, db: Database, max_output_length: int = DEFAULT_MAX_OUTPUT_LENGTH) -> None:
        """Initialize AuditLogger with database handle and maximum output length."""
        self.db = db
        self.max_output_length = max_output_length

    def _truncate_output(self, output: str | None) -> str | None:
        """Truncate execution output to a reasonable size before storage."""
        if output is None:
            return None
        if len(output) > self.max_output_length:
            return output[: self.max_output_length] + "\n... [truncated]"
        return output

    async def log_inspection(
        self,
        action: ActionRequest,
        decision: SecurityDecision,
        ai_explanation: str | None = None,
    ) -> AuditEntry:
        """Log an action inspection (no execution performed).

        Args:
            action: The proposed ActionRequest.
            decision: The SecurityDecision result from policy evaluation.
            ai_explanation: Optional explanation generated by AI risk analyzer.

        Returns:
            The created, redacted AuditEntry.
        """
        action_type_str = (
            action.action_type.value
            if isinstance(action.action_type, ActionType)
            else str(action.action_type)
        )
        action_hash = decision.action_hash or action.compute_hash()

        # Determine execution status based on policy decision
        if decision.decision == Decision.BLOCK:
            execution_status = "blocked"
        else:
            execution_status = "not_executed"

        approval_status = (
            ApprovalStatus.PENDING
            if decision.decision == Decision.REQUIRE_APPROVAL or decision.requires_approval
            else None
        )

        entry = AuditEntry(
            entry_id=str(uuid.uuid4()),
            action_type=action_type_str,
            action_summary=action.summary(),
            action_hash=action_hash,
            decision=decision.decision,
            risk_category=decision.risk_category,
            matched_policies=list(decision.matched_policies),
            explanation=decision.explanation,
            ai_explanation=ai_explanation,
            approval_status=approval_status,
            approval_id=None,
            execution_status=execution_status,
            execution_output=None,
            was_simulated=False,
            timestamp=datetime.now(timezone.utc),
            duration_ms=None,
        )

        # Redact any secrets before database persistence
        redacted = entry.redact()

        entry_dict = {
            "entry_id": redacted.entry_id,
            "action_type": redacted.action_type,
            "action_summary": redacted.action_summary,
            "action_hash": redacted.action_hash,
            "decision": (
                redacted.decision.value
                if isinstance(redacted.decision, Decision)
                else str(redacted.decision)
            ),
            "risk_category": (
                redacted.risk_category.value
                if isinstance(redacted.risk_category, RiskCategory)
                else str(redacted.risk_category)
            ),
            "matched_policies": redacted.matched_policies,
            "explanation": redacted.explanation,
            "ai_explanation": redacted.ai_explanation,
            "approval_status": (
                redacted.approval_status.value
                if isinstance(redacted.approval_status, ApprovalStatus)
                else redacted.approval_status
            ),
            "approval_id": redacted.approval_id,
            "execution_status": redacted.execution_status,
            "execution_output": redacted.execution_output,
            "was_simulated": redacted.was_simulated,
            "timestamp": redacted.timestamp.isoformat(),
            "duration_ms": redacted.duration_ms,
        }

        await self.db.insert_audit_entry(entry_dict)
        return redacted

    async def log_execution(
        self,
        action: ActionRequest,
        decision: SecurityDecision,
        execution_status: str,
        execution_output: str | None = None,
        duration_ms: int | None = None,
        was_simulated: bool = False,
        approval_id: str | None = None,
    ) -> AuditEntry:
        """Log an action execution with its execution result.

        Args:
            action: The executed ActionRequest.
            decision: The original SecurityDecision for this action.
            execution_status: Execution result string (e.g. 'success', 'failed', 'timeout').
            execution_output: Standard output / error output from execution.
            duration_ms: Time taken to execute the action in milliseconds.
            was_simulated: Whether the action was simulated (dry-run).
            approval_id: The approval record ID if this action required approval.

        Returns:
            The created, redacted AuditEntry.
        """
        action_type_str = (
            action.action_type.value
            if isinstance(action.action_type, ActionType)
            else str(action.action_type)
        )
        action_hash = decision.action_hash or action.compute_hash()
        truncated_output = self._truncate_output(execution_output)

        approval_status: ApprovalStatus | None = None
        if approval_id is not None:
            approval_status = ApprovalStatus.APPROVED
        elif decision.decision == Decision.REQUIRE_APPROVAL or decision.requires_approval:
            approval_status = ApprovalStatus.PENDING

        entry = AuditEntry(
            entry_id=str(uuid.uuid4()),
            action_type=action_type_str,
            action_summary=action.summary(),
            action_hash=action_hash,
            decision=decision.decision,
            risk_category=decision.risk_category,
            matched_policies=list(decision.matched_policies),
            explanation=decision.explanation,
            ai_explanation=None,
            approval_status=approval_status,
            approval_id=approval_id,
            execution_status=execution_status,
            execution_output=truncated_output,
            was_simulated=was_simulated,
            timestamp=datetime.now(timezone.utc),
            duration_ms=duration_ms,
        )

        # Redact secrets before saving
        redacted = entry.redact()

        entry_dict = {
            "entry_id": redacted.entry_id,
            "action_type": redacted.action_type,
            "action_summary": redacted.action_summary,
            "action_hash": redacted.action_hash,
            "decision": (
                redacted.decision.value
                if isinstance(redacted.decision, Decision)
                else str(redacted.decision)
            ),
            "risk_category": (
                redacted.risk_category.value
                if isinstance(redacted.risk_category, RiskCategory)
                else str(redacted.risk_category)
            ),
            "matched_policies": redacted.matched_policies,
            "explanation": redacted.explanation,
            "ai_explanation": redacted.ai_explanation,
            "approval_status": (
                redacted.approval_status.value
                if isinstance(redacted.approval_status, ApprovalStatus)
                else redacted.approval_status
            ),
            "approval_id": redacted.approval_id,
            "execution_status": redacted.execution_status,
            "execution_output": redacted.execution_output,
            "was_simulated": redacted.was_simulated,
            "timestamp": redacted.timestamp.isoformat(),
            "duration_ms": redacted.duration_ms,
        }

        await self.db.insert_audit_entry(entry_dict)
        return redacted

    async def get_entries(
        self,
        entry_id: str | None = None,
        decision: str | None = None,
        action_type: str | None = None,
        since_minutes: int | None = None,
        limit: int = 50,
    ) -> list[AuditEntry]:
        """Query audit entries with optional filters.

        Args:
            entry_id: Filter by exact entry ID.
            decision: Filter by decision value (ALLOW, BLOCK, REQUIRE_APPROVAL).
            action_type: Filter by action type (shell_command, file_write, etc.).
            since_minutes: Include only entries from the last N minutes.
            limit: Maximum number of entries to retrieve (default 50).

        Returns:
            List of matching AuditEntry objects ordered from newest to oldest.
        """
        rows = await self.db.get_audit_entries(
            entry_id=entry_id,
            decision=decision,
            action_type=action_type,
            since_minutes=since_minutes,
            limit=limit,
        )
        return [self._to_entry(row) for row in rows]

    async def get_stats(self) -> dict[str, int]:
        """Get aggregate dashboard overview statistics.

        Returns:
            Dictionary with counts for 'total', 'allowed', 'blocked', and 'require_approval'.
        """
        raw_stats = await self.db.get_audit_stats()
        return {
            "total": int(raw_stats.get("total") or 0),
            "allowed": int(raw_stats.get("allowed") or 0),
            "blocked": int(raw_stats.get("blocked") or 0),
            "require_approval": int(raw_stats.get("require_approval") or 0),
        }

    async def get_recent(self, limit: int = 10) -> list[AuditEntry]:
        """Get most recent audit entries.

        Args:
            limit: Maximum number of entries to retrieve (default 10).

        Returns:
            List of the most recent AuditEntry objects.
        """
        return await self.get_entries(limit=limit)

    @staticmethod
    def _to_entry(data: dict[str, Any]) -> AuditEntry:
        """Convert a database row dictionary to an AuditEntry model instance."""
        payload = dict(data)
        if isinstance(payload.get("matched_policies"), str):
            try:
                payload["matched_policies"] = json.loads(payload["matched_policies"])
            except Exception:
                payload["matched_policies"] = []

        entry = AuditEntry.model_validate(payload)
        if entry.timestamp and entry.timestamp.tzinfo is None:
            entry.timestamp = entry.timestamp.replace(tzinfo=timezone.utc)
        return entry
